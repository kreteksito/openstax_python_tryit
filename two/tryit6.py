"""Area of a triangle
1. Calculate the area of a triangle with base = 7 and height = 3.5.
2. Round the triangle's area to one decimal place.
3. Round the triangle's area to the nearest integer value.
"""
# be use the formula for the area of a triangle
base = 7
height = 3.5
area = base * height/2

# print using round() function
print ("Triangle's area:", area)
print ("Triangle's area rounded to one decimal place:", round(area,1))
print ("Triangle's area rounded to the nearest integer value:", round(area))